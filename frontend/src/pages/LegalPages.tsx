import type { ReactNode } from 'react';
import { Link } from 'react-router-dom';
import { api } from '../api';
import { useAsync } from '../components/useAsync';
import { useTitle } from '../components/useTitle';

function LegalLayout({ title, updated, children }: { title: string; updated: string; children: ReactNode }) {
  return (
    <main className="legal">
      <Link to="/" className="legal-back">
        ← На главную
      </Link>
      <h1>{title}</h1>
      <p className="muted small">Обновлено {updated}</p>
      <div className="markdown">{children}</div>
    </main>
  );
}

function Contact() {
  const site = useAsync(api.site, []);
  const email = site.status === 'ready' ? site.data.contactEmail : null;
  if (!email) return null;
  return (
    <>
      <h2>Связь</h2>
      <p>
        Вопросы и предложения: <a href={`mailto:${email}`}>{email}</a>.
      </p>
    </>
  );
}

